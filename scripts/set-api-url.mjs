// Writes src/environments/environment.production.ts for the production build.
// The API address comes from the API_URL variable (set it in Vercel > Settings > Environment Variables);
// without it the shared demo API is used. The URL is public configuration, never a secret.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DEFAULT_API_URL = 'https://rumbo-api-demo.onrender.com/api/v1';
const API_PATH = '/api/v1';

/** Accepts `https://host`, `https://host/` or `https://host/api/v1` and returns the full API base URL. */
export function resolveApiUrl(raw) {
  const value = (raw ?? '').trim();
  if (!value) return DEFAULT_API_URL;
  let url;
  try { url = new URL(value); } catch { throw new Error(`API_URL is not a valid URL: "${value}"`); }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') {
    throw new Error(`API_URL must start with http:// or https://, got "${url.protocol}"`);
  }
  if (url.search || url.hash) throw new Error('API_URL must not include a query string or a fragment');
  const path = url.pathname.replace(/\/+$/, '');
  const base = `${url.origin}${path}`;
  return base.endsWith(API_PATH) ? base : `${base}${API_PATH}`;
}

export function environmentSource(apiUrl) {
  return `// Generated by scripts/set-api-url.mjs from the API_URL variable. Do not edit by hand.
export const environment = {
  production: true,
  apiUrl: '${apiUrl}'
};
`;
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const apiUrl = resolveApiUrl(process.env.API_URL);
  writeFileSync(new URL('../src/environments/environment.production.ts', import.meta.url), environmentSource(apiUrl));
  console.log(`production apiUrl: ${apiUrl}${process.env.API_URL ? ' (from API_URL)' : ' (default)'}`);
}
